function agm_element_fields()
{
    if (!current_user_can('edit_theme_options')) { return []; }
    $fields = [];
    foreach (agm_content_sections() as $section => $config) {
        foreach ($config['fields'] as $key => $field) {
            $type = agm_content_field_type($field);
            $fields[$key] = ['section' => $section, 'label' => is_array($field) ? $field[0] : $field, 'type' => $type, 'value' => agm_content_current($key, $field)];
        }
    }
    return $fields;
}
function agm_element_menu_items()
{
    if (!current_user_can('edit_theme_options')) { return []; }
    $items = [];
    foreach (wp_get_nav_menus() as $menu) {
        foreach (wp_get_nav_menu_items($menu->term_id) ?: [] as $item) {
            $items[$item->ID] = ['label' => $item->title, 'url' => admin_url('nav-menus.php?menu=' . $menu->term_id . '&agm_menu_item=' . $item->ID)];
        }
    }
    return $items;
}
